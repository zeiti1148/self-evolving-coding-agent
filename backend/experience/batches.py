"""One validated extraction per task; records and their ordered links commit together."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
from uuid import uuid4

from pydantic import ValidationError

from backend.shared import ApplicationError, ErrorCode, Experience, ExperienceCreate
from .database import connect, storage_error
from .store import COLUMNS, _insert, _new_experience, _uuid, decode_row, validation_error


def canonical(value) -> str:
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def save_batch(path: Path, items: list[ExperienceCreate], *, source_task_id: str) -> list[Experience]:
    source_task_id = _uuid(source_task_id)
    if not isinstance(items, list) or not 1 <= len(items) <= 5:
        raise validation_error("A batch requires between 1 and 5 experiences.")
    try:
        validated = [ExperienceCreate.model_validate(item.model_dump()) for item in items]
        payload = [item.model_dump(mode="json", exclude={"batch_id"}) for item in validated]
        payload_hash = hashlib.sha256(canonical(payload).encode("utf-8")).hexdigest()
    except (ValidationError, AttributeError, UnicodeError, TypeError, ValueError):
        raise validation_error("Invalid experience batch; nothing was saved.") from None
    first = validated[0]
    identities = {(item.language, item.repository_id, item.source_revision) for item in validated}
    knowledge = set()
    for item in validated:
        if (item.schema_version != 3 or item.scope != "project" or item.reuse_status != "active"
                or item.source_task_id != source_task_id or not item.evidence
                or any(e.source_task_id != source_task_id for e in item.evidence)
                or item.evidence != first.evidence or len(identities) != 1):
            raise validation_error("Batch records must share one repository, task and final verification.")
        if item.batch_id or item.merged_from or item.derived_from or item.supersedes_id:
            raise validation_error("Batch provenance is generated by the program.")
        # A new title, tag or verification label does not create independent knowledge.
        rule = canonical({"root_cause": item.root_cause, "solution": item.solution,
                          "issues": [issue.model_dump() for issue in item.issues],
                          "applicability": item.applicability})
        if rule in knowledge:
            raise validation_error("Duplicate knowledge in batch; nothing was saved.")
        knowledge.add(rule)
    with connect(path) as connection:
        connection.execute("BEGIN IMMEDIATE")
        existing = connection.execute("SELECT batch_id, payload_hash FROM experience_batches WHERE source_task_id=?",
                                      (source_task_id,)).fetchone()
        if existing:
            if existing["payload_hash"] != payload_hash:
                raise ApplicationError(ErrorCode.EXPERIENCE_CONFLICT, "Task already has a different batch.")
            ids = connection.execute("SELECT experience_id FROM experience_batch_items WHERE batch_id=? ORDER BY ordinal",
                                     (existing["batch_id"],)).fetchall()
            if len(ids) != len(validated):
                raise storage_error()
            saved = []
            for row in ids:
                record = connection.execute(f"SELECT {COLUMNS} FROM experiences WHERE id=?", (row[0],)).fetchone()
                if record is None:
                    raise storage_error()
                saved.append(decode_row(record))
            return saved
        batch_id = str(uuid4())
        connection.execute("INSERT INTO experience_batches VALUES (?, ?, ?, ?)",
                           (batch_id, source_task_id, payload_hash, datetime.now(timezone.utc).isoformat()))
        saved = []
        for ordinal, item in enumerate(validated):
            record = _new_experience(item.model_copy(update={"batch_id": batch_id}))
            _insert(connection, record)
            connection.execute("INSERT INTO experience_batch_items VALUES (?, ?, ?)", (batch_id, ordinal, record.id))
            saved.append(record)
        return saved
